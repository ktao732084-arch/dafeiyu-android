"""Generate src/com/xiaoxiao/pet/MemoryRules.java from the vendored memory engine.

LocalEngine (the phone's offline write path) uses the same keyword lists, regular
expressions and thresholds as the Python engine. Run this after sync-memory-service.py:

    python tools/export-memory-rules.py
"""
import json
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / 'memory-service/upstream/src'))
import memory  # noqa: E402
import noise_filter  # noqa: E402

upstream = json.loads((root / 'memory-service/UPSTREAM.json').read_text(encoding='utf-8'))


def regex(pattern):
    """Python re syntax to java.util.regex: only the 8-digit \\U escape differs in these rules."""
    return re.sub(r'\\U([0-9A-Fa-f]{8})', lambda m: '\\x{' + m.group(1).lstrip('0') + '}', pattern)


def literal(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def strings(values, convert=lambda s: s):
    return '{' + ','.join(literal(convert(v)) for v in values) + '}'


nf = noise_filter.NoiseFilter
rules = memory.IMPORTANCE_RULES
order = ['identity_health_safety', 'preference_relation_status', 'project_task_goal', 'temporary']
lines = [
    'package com.xiaoxiao.pet;',
    '',
    '// Generated by tools/export-memory-rules.py from memory-service/upstream at ' + upstream['revision'] + '. Do not edit.',
    'final class MemoryRules {',
    '    static final String[] SECRET_PATTERNS=' + strings(noise_filter.SECRET_PATTERNS, regex) + ';',
    '    static final String[][] ENGINE_NOISE=' + '{' + ','.join(
        '{' + literal(category) + ',' + ','.join(literal(regex(p)) for p in patterns) + '}'
        for category, patterns in memory.NOISE_PATTERNS.items()) + '};',
    '    static final String[] FILTER_PATTERNS=' + strings(nf.NOISE_PATTERNS, regex) + ';',
    '    static final String[] FILTER_KEYWORDS=' + strings(nf.NOISE_KEYWORDS) + ';',
    '    static final String[] CONVERSATION_NOISE=' + strings(nf.CONVERSATION_NOISE, regex) + ';',
    '    static final String[] FACT_MARKERS=' + strings(nf.FACT_MARKERS) + ';',
    '    static final String QUESTION_PATTERN=' + literal(regex(nf.QUESTION_PATTERN)) + ';',
    '    static final String[] DISTRACTION_PATTERNS=' + strings(nf.DISTRACTION_PATTERNS, regex) + ';',
    '    static final String[] CATEGORIES=' + strings(order) + ';',
    '    static final String[][] CATEGORY_KEYWORDS={' + ','.join(strings(rules[c]['keywords']) for c in order) + '};',
    '    static final double[] CATEGORY_SCORES={' + ','.join(repr(float(rules[c]['score'])) for c in order) + '};',
    '    static final double GENERAL_SCORE=' + repr(float(rules['general_fact']['score'])) + ';',
    '    static final String[][] SIGNAL_KEYWORDS={' + ','.join(strings(s['keywords']) for s in memory.EXPLICIT_SIGNALS.values()) + '};',
    '    static final double[] SIGNAL_BOOSTS={' + ','.join(repr(float(s['boost'])) for s in memory.EXPLICIT_SIGNALS.values()) + '};',
    '    static final String[] OVERRIDE_TIER1=' + strings(memory.OVERRIDE_SIGNALS_TIER1) + ';',
    '    static final String[] OVERRIDE_TIER2=' + strings(memory.OVERRIDE_SIGNALS_TIER2) + ';',
    '    static final double MIN_OVERLAP=' + repr(float(memory.DEDUP_CONFIG['min_overlap_ratio'])) + ',MERGE_OVERLAP=' + repr(float(memory.DEDUP_CONFIG['merge_overlap_ratio']))
    + ',TIER1_PENALTY=' + repr(float(memory.DEDUP_CONFIG['tier1_penalty'])) + ',TIER2_PENALTY=' + repr(float(memory.DEDUP_CONFIG['tier2_penalty'])) + ';',
    '    static final String[] PERMANENT_CATEGORIES=' + strings(sorted(memory.PERMANENT_CATEGORIES)) + ';',
    '}',
    '',
]
target = root / 'src/com/xiaoxiao/pet/MemoryRules.java'
target.write_text('\n'.join(lines), encoding='utf-8')
print('Wrote', target.relative_to(root))
